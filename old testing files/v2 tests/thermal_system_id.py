#!/usr/bin/env python3
"""
thermal_system_id.py

Thermal system identification for the Pi geothermal-cooling rig.

What this does
---------------
1. Loads a benchmark log (CSV) with a timestamp/elapsed-time column, a
   temperature column (CPU temp), and a load/phase marker that tells us
   when a step change happened (e.g. idle -> full load, full load ->
   idle, pump on -> pump off).
2. Auto-detects step events from the load/phase column (or accepts
   explicit step timestamps from the command line).
3. Fits die temperature as delta_T = T_die - T_ambient rather than the
   absolute temperature whenever an ambient column is available, so
   ambient drift across trials doesn't bleed into the R_th estimate.
   Falls back to absolute temperature if no ambient column is given.
4. For each step, fits a two-exponential response:
       dT(t) = dT_ss + A1*exp(-t/tau1) + A2*exp(-t/tau2)
   tau1 is seeded short (fast die/heatsink transient) and tau2 long
   (slow coolant/reservoir tail), with bounds constraining tau1 < tau2
   so the optimizer can't swap the two branches and land on a
   degenerate duplicate. This is now the only model this script fits --
   see CHANGE LOG below for why the single-exponential option was
   removed rather than kept as a fallback.
5. Computes per-branch thermal resistance R_i = |A_i| / delta_Q and
   capacitance C_i = tau_i / R_i for each branch, plus a summed
   R_thermal_c_per_w = R1 + R2 for a single number comparable to
   published single-node literature values. Q here is q_cpu_w -- CPU/SoC
   electrical power, taken as a direct estimate of heat generated by the
   die (see geo_common.compute_q_cpu_w) -- not a fluid-side heat-removed
   number. This module doesn't care where Q came from, only that
   whatever column you point --power-col at represents heat into the
   node being fit. R is computed against delta_Q = Q_ss - Q_baseline
   (the actual size of the power step), not Q_ss alone -- see
   estimate_baseline_power() for why that distinction matters.
6. Produces:
     - a CSV summary table (one row per step, per cooling condition)
     - a figure overlaying raw data + the two-exponential fit for each step
     - a benchmark comparison figure: your tau2 (dominant/slow time
       constant) vs. published server / CRAC time constants
     - a markdown table you can drop straight into the manuscript

Expected input CSV columns (rename via --col-* flags if yours differ):
    time_s        : elapsed seconds since test start (float)
    cpu_temp_c     : CPU temperature, deg C
    ambient_c      : room/ambient temperature, deg C (optional but
                      recommended -- enables delta_T fitting)
    q_cpu_w        : CPU/SoC electrical power draw, W -- used as Q for
                      the R_th/C_th calculation (optional; needed for R
                      and C, not for the tau fit itself)
    cooling_type   : string label, e.g. "none", "fan", "loop"
    load_state     : string or int marker for phase, e.g. "idle"/"load",
                      or 0/1. Used to auto-detect step transitions.

You do not need every column filled for every row; the script only
requires time_s, one temperature column, and load_state (or explicit
--steps timestamps) to run the tau fit. q_cpu_w is needed for R and C.

A step needs at least 8 samples to attempt a fit at all, and the
two-exponential model (5 free parameters) needs a reasonable number of
samples beyond that to converge to something meaningful -- short or
sparsely-sampled windows are more likely to fail to converge, or to
converge onto a near-degenerate pair of branches (tau1 approx tau2). See
CHANGE LOG for how that's now handled given there's no single-exponential
fallback anymore.

Usage
-----
    python3 thermal_system_id.py --input rig_log.csv --outdir results \
        --temp-col cpu_temp_c --ambient-col ambient_c --cooling-col cooling_type

    # or, if you already know exactly when your steps happened:
    python3 thermal_system_id.py --input rig_log.csv --outdir results \
        --temp-col cpu_temp_c --ambient-col ambient_c --steps 0,1200,2400,3600

This module is also imported directly by step_load_test.py, which calls
analyze_step() on each step/hold transition as soon as it's captured,
rather than round-tripping through a saved CSV.

CHANGE LOG (this file)
-----------------------
- Removed the single-exponential model entirely, along with the AICc /
  residual-runs-test model-selection machinery that used to decide
  between single- and two-exponential per step. Every step is now fit
  with the two-exponential model only. Rationale: the geothermal
  condition's chain of thermal masses (die -> heatsink -> coolant ->
  loop -> reservoir) is the physically motivated model across all
  conditions here, not just geothermal -- fan and no_cooling have their
  own fast (die/heatsink) and slow (surrounding air volume) branches too,
  just with less separation between tau1 and tau2. Fitting one model
  throughout means every trial's R_th/tau numbers are computed the same
  way and are directly comparable, rather than some rows being
  single-exponential and others two-exponential depending on whether a
  given step happened to clear the old AICc threshold. If a step's window
  is too short or too sparse to resolve two real time constants, the fit
  will either fail to converge (tau1_two_exp_s/tau2_two_exp_s come back
  NaN, and the step is flagged in the console) or land on a near-
  degenerate pair (tau1 approx tau2) -- both are now surfaced as
  warnings rather than silently falling back to a different model, since
  there is no fallback model anymore. If you see that warning, the fix is
  a longer --window / --fit-window on that phase, not a different model.
- Fixed R_thermal_c_per_w / R1_two_exp_c_per_w / R2_two_exp_c_per_w being
  computed as |amplitude| / Q_ss (the absolute load-phase power). The
  fitted transient amplitude (A1, A2) is the size of the response to the
  STEP in power, i.e. proportional to (Q_load - Q_idle), not to Q_load
  alone. Whenever idle power isn't negligible relative to load power,
  dividing by Q_ss alone understates R. R is now computed from
  delta_Q = Q_ss - Q_baseline, where Q_baseline is estimated from the
  power samples immediately preceding the step. Q_ss_w is still reported
  as before, plus new Q_baseline_w and delta_Q_w columns for
  transparency.
- --power-col (and run_thermal_sysid's power_col default) changed from
  "power_w" (combined Pi + pump electrical draw) to "q_cpu_w" (CPU/SoC
  electrical power only). R_th/C_th are meant to characterize the die's
  thermal path, so Q should be the heat the die is actually generating,
  not the pump's own power consumption. This also removes the module's
  prior dependence on a fluid-side heat-removed number -- Q now comes
  straight from geo_common.compute_q_cpu_w(), which just reflects
  measured Pi electrical power back as an estimate of Q_cpu. The
  Q_baseline / delta_Q correction above applies identically to this new
  Q source -- if anything it matters more, since idle CPU power is a
  larger fraction of load CPU power than idle total-power was.
"""

